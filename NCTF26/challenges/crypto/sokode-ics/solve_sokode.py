INV = [0] * 256
for i, v in enumerate(SBOX): INV[v] = i
RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

def gmul(a, b):
    p = 0
    for _ in range(8):
        if b & 1: p ^= a
        hi = a & 0x80; a = (a << 1) & 0xff
        if hi: a ^= 0x1b
        b >>= 1
    return p

# Une faute f sur la ligne r d'une colonne donne, après MixColumns,
# la COLONNE r de la matrice multipliée par f.
MC_COLS = [(2, 1, 1, 3), (3, 2, 1, 1), (1, 3, 2, 1), (1, 1, 3, 2)]

def key_exp(key):
    w = list(key)
    for i in range(4, 44):
        t = w[(i-1)*4:i*4]
        if i % 4 == 0:
            t = t[1:] + t[:1]; t = [SBOX[b] for b in t]; t[0] ^= RCON[i//4 - 1]
        for j in range(4): w.append(w[(i-4)*4 + j] ^ t[j])
    return [bytes(w[i*16:(i+1)*16]) for i in range(11)]

def inv_key_exp(k10):
    """Inverse du key schedule : K10 -> K0."""
    words = {40 + i: list(k10[4*i:4*i+4]) for i in range(4)}
    for i in range(43, 3, -1):
        t = words[i-1]
        if i % 4 == 0:
            t = t[1:] + t[:1]; t = [SBOX[b] for b in t]; t[0] ^= RCON[i//4 - 1]
        words[i-4] = [words[i][j] ^ t[j] for j in range(4)]
    return bytes(sum((words[i] for i in range(4)), []))

def encrypt(pt, key):
    rks = key_exp(key)
    s = [pt[i] ^ rks[0][i] for i in range(16)]           # index = ligne + 4*colonne
    for rnd in range(1, 11):
        s = [SBOX[x] for x in s]
        s = [s[r + 4*((c + r) % 4)] for c in range(4) for r in range(4)]
        if rnd != 10:
            n = [0] * 16
            for c in range(4):
                b = s[4*c:4*c+4]
                n[4*c:4*c+4] = [gmul(2,b[0])^gmul(3,b[1])^b[2]^b[3], b[0]^gmul(2,b[1])^gmul(3,b[2])^b[3],
                                b[0]^b[1]^gmul(2,b[2])^gmul(3,b[3]), gmul(3,b[0])^b[1]^b[2]^gmul(2,b[3])]
            s = n
        s = [s[i] ^ rks[rnd][i] for i in range(16)]
    return bytes(s)

def key_candidates(c, cf, col):
    """Ensemble des 4-uplets d'octets de K10 compatibles avec une paire (C, C')."""
    pos = [i + 4*((col - i) % 4) for i in range(4)]       # ligne i -> position après ShiftRows R10
    out = set()
    for frow in range(4):
        for f in range(1, 256):
            per = []
            for i in range(4):
                d = gmul(MC_COLS[frow][i], f)
                per.append([k for k in range(256) if INV[c[pos[i]] ^ k] ^ INV[cf[pos[i]] ^ k] == d])
                if not per[-1]: break
            else:
                out.update(itertools.product(*per))
    return pos, out

def main(path):
    vals = dict(re.findall(r'^(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)', open(path).read(), re.M))
    h = lambda k: bytes.fromhex(vals[k][2:].zfill(32))
    pairs = [(h(f"PT_{n:02d}"), h(f"CT_{n:02d}"), h(f"CT_{n:02d}_FAULT"), int(vals[f"FAULT_COL_{n:02d}"]))
             for n in range(1, 17)]

    k10 = [None] * 16
    for col in range(4):
        total = None
        for _, c, cf, fc in pairs:
            if fc != col: continue
            pos, cands = key_candidates(c, cf, col)
            total = cands if total is None else total & cands
        print(f"[+] Colonne {col} : {len(total)} candidat(s) restant(s)")
        assert len(total) == 1
        for i, b in enumerate(next(iter(total))): k10[pos[i]] = b

    k10 = bytes(k10)
    key = inv_key_exp(k10)
    print(f"[+] K10 = {k10.hex()}")
    print(f"[+] Clé AES-128 (K0) = {key.hex()}")
    ok = all(encrypt(pt, key) == ct for pt, ct, _, _ in pairs)
    print(f"[+] Vérification sur les 16 paires PT/CT : {'OK' if ok else 'ÉCHEC'}")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "challenge.txt")
